"""Publish source-checked workflows as review-gate-style SVG cards.

Run with Show Your Work's render extra (see docs/workflows/intro.md).
Mermaid supplies graph layout only; the published SVG uses native text and cards.
No browser scripts, foreignObject, external fonts, or runtime dependencies ship.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import textwrap
from datetime import datetime, timezone
from html import escape
from pathlib import Path
import xml.etree.ElementTree as ET

import mermaidx
from show_your_work.checks import check_dir
from show_your_work.header import parse_header
from show_your_work.render import Diagram, build_index, build_readme, serialize_index

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs/workflows"
NS = {"s": "http://www.w3.org/2000/svg"}
CONFIG = """---
config:
  fontFamily: monospace
  flowchart:
    htmlLabels: false
    wrappingWidth: 180
    padding: 20
    rankSpacing: 38
    nodeSpacing: 38
---
"""


def layout(source: str):
    # The catalog uses action boxes and decision diamonds. Both become cards,
    # with a blue border and explicit GATE label retaining decision semantics.
    definitions = re.findall(r"\b(\w+)(\[[^\]\n]+\]|\{[^}\n]+\})", source)
    labels = {key: value[1:-1] for key, value in definitions}
    gates = {key for key, value in definitions if value.startswith("{")}
    body = re.sub(r"\{([^}\n]+)\}", r"[\1]", source)
    root = ET.fromstring(mermaidx.render(CONFIG + body).svg())
    nodes = []
    for group in root.findall('.//s:g[@class="nodes"]/s:g', NS):
        key = re.search(r"-flowchart-(\w+)-\d+$", group.attrib["id"]).group(1)
        rect = group.find("s:rect", NS)
        x, y = map(float, re.findall(r"[-\d.]+", group.attrib["transform"]))
        w, h = float(rect.attrib["width"]), float(rect.attrib["height"])
        lines = textwrap.wrap(labels[key], max(12, int((w - 32) / 7.8)))
        needed = len(lines) * 16 + (20 if key in gates else 0)
        if needed > h - 10:
            raise ValueError(f"Label does not fit: {key}: {labels[key]}")
        nodes.append((key, x, y, w, h, lines, key in gates))
    if set(labels) != {n[0] for n in nodes}:
        raise ValueError("Unsupported node syntax or missing layout node")
    edges = root.findall('.//s:g[@class="edgePaths"]/s:path', NS)
    if len(edges) != source.count("-->"):
        raise ValueError("Layout dropped an edge")
    edge_labels = []
    for group in root.findall('.//s:g[@class="edgeLabels"]/s:g', NS):
        label = "".join(group.itertext()).strip()
        if label:
            x, y = map(float, re.findall(r"[-\d.]+", group.attrib["transform"]))
            edge_labels.append((x, y, label))
    return root.attrib["viewBox"], nodes, edges, edge_labels


def svg(diagram: Diagram, geometry, theme: str) -> str:
    viewbox, nodes, edges, edge_labels = geometry
    vx, vy, vw, vh = map(float, viewbox.split())
    bg, border, line, blue, muted = (
        ("#161C26", "#29313F", "#384153", "#6E9BFF", "#9AA5B8")
        if theme == "dark" else
        ("#FFFFFF", "#D4DBE8", "#C0C9DA", "#3355E0", "#6E778C")
    )
    width, height = vw + 40, vh + 76
    out = [f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width:.3f} {height:.3f}" role="img" aria-labelledby="title desc" font-family="ui-monospace,'Cascadia Code','SF Mono',Consolas,monospace">
<title id="title">{escape(diagram.header.title)}</title>
<desc id="desc">{escape(diagram.header.alt)}</desc>
<!-- Source SHA-256: {diagram.sha256}; generated by tools/render-workflow-cards.py -->
<defs><marker id="arrow" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="8" markerHeight="8" markerUnits="userSpaceOnUse" orient="auto"><path d="M0,0 L10,5 L0,10 Z" fill="{blue}"/></marker><filter id="shadow" x="-20%" y="-45%" width="140%" height="190%"><feDropShadow dx="0" dy="2" stdDeviation="4" flood-opacity=".16"/></filter></defs>
<rect x="6" y="6" width="{width-12:.3f}" height="{height-12:.3f}" rx="16" fill="{bg}" stroke="{border}" stroke-width="1.5"/>
<text x="26" y="32" fill="{muted}" font-size="11" letter-spacing=".12em">{escape(diagram.id.upper())}</text>
<g transform="translate({20-vx:.3f},{54-vy:.3f})">''']
    for edge in edges:
        out.append(f'<path data-edge="{escape(edge.get("data-id", ""))}" d="{escape(edge.attrib["d"])}" fill="none" stroke="{blue}" stroke-width="1.8" marker-end="url(#arrow)"/>')
    for x, y, label in edge_labels:
        out.append(f'<text x="{x:.3f}" y="{y+4:.3f}" text-anchor="middle" fill="{muted}" font-size="11" stroke="{bg}" stroke-width="6" paint-order="stroke">{escape(label)}</text>')
    for key, x, y, w, h, lines, gate in nodes:
        out.append(f'<g data-node="{key}"><rect x="{x-w/2:.3f}" y="{y-h/2:.3f}" width="{w:.3f}" height="{h:.3f}" rx="10" fill="{bg}" stroke="{blue if gate else line}" stroke-width="1.4" filter="url(#shadow)"/>')
        top = y - (len(lines)*16 + (20 if gate else 0))/2
        if gate:
            out.append(f'<text x="{x-w/2+16:.3f}" y="{top+9:.3f}" fill="{muted}" font-size="9" letter-spacing=".12em">GATE</text>')
            top += 20
        for i, label in enumerate(lines):
            out.append(f'<text x="{x-w/2+16:.3f}" y="{top+12+i*16:.3f}" fill="{blue}" font-size="13" font-weight="600">{escape(label)}</text>')
        out.append('</g>')
    return "\n".join(out + ['</g></svg>', ''])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare all outputs without writing")
    args = parser.parse_args()
    report = check_dir(TARGET)
    if report.failed:
        raise ValueError(f"Show Your Work source checks failed: {report}")
    diagrams = []
    outputs = {}
    for path in sorted(TARGET.glob("*.mmd")):
        source = path.read_text(encoding="utf-8")
        diagram = Diagram(path.stem, parse_header(source), source,
                          hashlib.sha256(source.encode()).hexdigest(), "mermaid")
        diagrams.append(diagram)
        geometry = layout(source)
        for theme in ("dark", "light"):
            outputs[TARGET / f"cards/{path.stem}-{theme}.svg"] = svg(diagram, geometry, theme)
    readme = build_readme(diagrams, (TARGET / "intro.md").read_text(encoding="utf-8"), "docs/workflows")
    readme = re.sub(r"<!--.*?-->", "<!-- GENERATED by tools/render-workflow-cards.py using Show Your Work. -->", readme, count=1, flags=re.S)
    for diagram in diagrams:
        picture = f'''<picture>
  <source media="(prefers-color-scheme: dark)" srcset="cards/{diagram.id}-dark.svg">
  <img alt="{escape(diagram.header.alt, quote=True)}" src="cards/{diagram.id}-light.svg">
</picture>

[Open full size](cards/{diagram.id}-dark.svg)'''
        readme = readme.replace('```mermaid\n'+diagram.text.rstrip()+'\n```', picture)
        for source in diagram.header.sources:
            readme = readme.replace(f'- `{source}`', f'- [`{source}`](../../{source})')
    readme = readme[:readme.index("\n## Regenerating\n")] + "\n## Regenerating\n\nUse the commands above. `--check` compares every SVG, the README, and the source index without writing.\n"
    outputs[TARGET / "README.md"] = readme
    previous = json.loads((TARGET / "workflows.json").read_text(encoding="utf-8"))
    index = build_index(diagrams, "docs/workflows", datetime.fromisoformat(previous["generated_at"]), previous=previous, target=TARGET)
    if index != previous:
        index["generated_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    outputs[TARGET / "workflows.json"] = serialize_index(index)
    stale = []
    for path, content in outputs.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    print(f"{len(diagrams)} workflows; {len(diagrams)*2} SVGs; {len(stale)} " + ("stale" if args.check else "updated"))
    if args.check and stale:
        print("\n".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
